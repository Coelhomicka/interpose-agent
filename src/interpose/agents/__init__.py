"""Teach coding agents how to use Interpose.

One set of instructions (``instructions.md``) is rendered into whatever each tool
reads:

* ``AGENTS.md`` — the cross-tool convention: Codex, Cursor, Devin, Antigravity,
  GitHub Copilot, Jules, Amp, Windsurf, Zed and others read it;
* ``CLAUDE.md`` and a Claude Code skill;
* ``GEMINI.md`` — Gemini CLI and Antigravity;
* a Cursor project rule.

Shared files get a marked block that is replaced in place on reinstall and removed
cleanly on uninstall; everything else in them is left alone. Tools configured only
through a settings screen (Devin's knowledge, Cursor's user rules) take the text
from ``interpose agents print``.

The instructions are advisory. Enforcement still comes from the broker, the
policies and the OS; an agent that ignores them gains nothing.
"""

from __future__ import annotations

from dataclasses import dataclass
from importlib import resources
from pathlib import Path

BEGIN = "<!-- BEGIN interpose: generated by `interpose agents install`; edits inside are replaced -->"
END = "<!-- END interpose -->"

SKILL_DESCRIPTION = (
    "How to call APIs and use credentials on a machine protected by Interpose. Use whenever a task "
    "needs an API key or token, makes an authenticated HTTP request, writes .env or SDK config with "
    "credentials, meets a secret:// reference or INTERPOSE_* variable, or gets a 403 PolicyViolation "
    "or [REDACTED] from the local broker."
)


def instructions() -> str:
    return resources.files(__package__).joinpath("instructions.md").read_text("utf-8")


def skill_document() -> str:
    return f"---\nname: interpose\ndescription: {SKILL_DESCRIPTION}\n---\n\n{instructions()}"


def cursor_rule() -> str:
    return (
        "---\n"
        "description: Interpose - how to use credentials and call APIs through the local broker\n"
        "alwaysApply: true\n"
        "---\n\n"
        f"{instructions()}"
    )


def upsert_block(existing: str, body: str) -> str:
    block = f"{BEGIN}\n\n{body.rstrip()}\n\n{END}\n"
    start, end = existing.find(BEGIN), existing.find(END)
    if start != -1 and end != -1 and end > start:
        return existing[:start] + block + existing[end + len(END):].lstrip("\n")
    if not existing.strip():
        return block
    return existing.rstrip("\n") + "\n\n" + block


def remove_block(existing: str) -> str:
    start, end = existing.find(BEGIN), existing.find(END)
    if start == -1 or end == -1 or end < start:
        return existing
    remaining = existing[:start].rstrip("\n") + "\n" + existing[end + len(END):].lstrip("\n")
    return remaining if remaining.strip() else ""


@dataclass(frozen=True)
class Target:
    """One file an agent reads. ``owned`` files belong to Interpose entirely;
    the others are shared and only carry a marked block."""

    path: Path
    tools: str
    owned: bool = False

    def render(self) -> str:
        if self.path.name == "SKILL.md":
            return skill_document()
        if self.path.suffix == ".mdc":
            return cursor_rule()
        return ""

    def install(self) -> str:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        if self.owned:
            new = self.render()
        else:
            current = self.path.read_text(encoding="utf-8") if self.path.exists() else ""
            new = upsert_block(current, instructions())
        existed = self.path.exists()
        self.path.write_text(new, encoding="utf-8")
        return "updated" if existed else "created"

    def remove(self) -> str | None:
        if not self.path.exists():
            return None
        if self.owned:
            self.path.unlink()
            if self.path.parent.name == "interpose" and not any(self.path.parent.iterdir()):
                self.path.parent.rmdir()
            return "removed"
        current = self.path.read_text(encoding="utf-8")
        remaining = remove_block(current)
        if remaining == current:
            return None
        if remaining:
            self.path.write_text(remaining, encoding="utf-8")
            return "cleaned"
        self.path.unlink()
        return "removed"


def project_targets(root: Path) -> list[Target]:
    return [
        Target(root / "AGENTS.md", "Codex, Cursor, Devin, Antigravity, Copilot, Jules, Amp, Windsurf"),
        Target(root / "CLAUDE.md", "Claude Code"),
        Target(root / "GEMINI.md", "Gemini CLI, Antigravity"),
        Target(root / ".cursor" / "rules" / "interpose.mdc", "Cursor", owned=True),
    ]


def global_targets(home: Path) -> list[Target]:
    """User-level files, only for tools that are installed (their folder exists)."""
    candidates = [
        (home / ".claude", Target(home / ".claude" / "skills" / "interpose" / "SKILL.md", "Claude Code (skill)",
                                  owned=True)),
        (home / ".codex", Target(home / ".codex" / "AGENTS.md", "Codex CLI")),
        (home / ".gemini", Target(home / ".gemini" / "GEMINI.md", "Gemini CLI, Antigravity")),
    ]
    return [target for tool_home, target in candidates if tool_home.is_dir()]
